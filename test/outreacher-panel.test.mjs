assert.deepEqual(Object.keys(statusPayload), ["available"]);
assert.equal(JSON.stringify(statusPayload).includes("sk_live"), false);
assert.match(checkout, /acq_can_edit/);
assert.doesNotMatch(page + landing, /service_role/);

