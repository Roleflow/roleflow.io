import assert from "node:assert/strict";
import fs from "node:fs";
import { normalizeHandle, outreacherPhase, sessionLabel, outreacherCopy, termCopy, soonParts, outreachControls, landingCta, readOutreachCheckoutStatus } from "../acquire/outreacher-page.js";
import { OUTREACH_PRICE_COPY, checkoutAvailable } from "../supabase/functions/_shared/outreacher-pricing.js";

const page = fs.readFileSync(new URL("../acquire/outreacher-page.js", import.meta.url), "utf8");
const app = fs.readFileSync(new URL("../acquire/app.js", import.meta.url), "utf8");
const landing = fs.readFileSync(new URL("../outreacher/index.html", import.meta.url), "utf8");
const live = fs.readFileSync(new URL("../supabase/functions/outreach-live/index.ts", import.meta.url), "utf8");
const checkout = fs.readFileSync(new URL("../supabase/functions/outreach-checkout/index.ts", import.meta.url), "utf8");

assert.equal(normalizeHandle("@North.Studio"), "north.studio");
assert.equal(normalizeHandle("bad handle"), "");
assert.equal(outreacherPhase({}), "start");
assert.equal(outreacherPhase({ machine: { status: "deleted" } }), "start");
assert.equal(outreacherPhase({ machine: { status: "provisioning", session_state: "unknown" } }), "setup");
assert.equal(outreacherPhase({ machine: { status: "awaiting_login", session_state: "unknown" } }), "login");
assert.equal(outreacherPhase({ machine: { status: "running", session_state: "ok" } }), "connected");
assert.equal(outreacherPhase({ machine: { status: "running", session_state: "checkpoint" } }), "reconnect");
assert.equal(outreacherPhase({ machine: { status: "running", session_state: "expired" } }), "reconnect");
assert.equal(outreacherPhase({ machine: { status: "running", session_state: "ok" }, outreacherConfig: { paused: true } }), "paused");
assert.equal(outreacherPhase({ machine: { status: "error" } }), "attention");
assert.equal(outreacherPhase({ machine: { status: "suspended" } }), "suspended");
assert.equal(sessionLabel(outreacherCopy("en"), { session_state: "unknown" }), "Needs login");
assert.equal(sessionLabel(outreacherCopy("es"), { session_state: "ok" }), "Conectado");

assert.match(page, /id: "outreach-setup"/);
assert.match(page, /id: "outreach-handle"/);
assert.match(page, /type: "checkbox"/);
assert.doesNotMatch(page, /type: "password"|Grok Bot|Zernio|Hetzner|noVNC/i);
assert.doesNotMatch(landing, /Grok Bot|Zernio|Hetzner|noVNC/i);
assert.match(landing, /name="robots" content="noindex"/);
assert.match(landing, /Contact us/);
assert.match(landing, /mailto:diego@roleflow.io/);
assert.match(app, /renderOutreacher\(ui\)/);
assert.match(app, /functions\/v1\/outreach-live/);
assert.match(app, /functions\/v1\/outreach-checkout/);
assert.match(fs.readFileSync(new URL("../supabase/config.toml", import.meta.url), "utf8"), /\[functions\.outreach-live\]\nverify_jwt = true/);
assert.match(checkout, /STRIPE_OUTREACH_SETUP_PRICE_ID/);
assert.match(checkout, /STRIPE_OUTREACH_GROWTH_PRICE_ID/);
assert.doesNotMatch(checkout, /STRIPE_OUTREACH_PRICE_ID/);
assert.match(checkout, /mode", "subscription"|checkoutSessionParams/);
assert.match(page, /\$249 setup \+ 10% of growth, 3-month minimum/);
assert.equal(outreacherCopy("en").price, OUTREACH_PRICE_COPY);
assert.equal(outreacherCopy("es").price, "$249 de alta + 10% del crecimiento, mínimo de 3 meses");
assert.notEqual(outreacherCopy("es").price, OUTREACH_PRICE_COPY);
assert.equal(outreacherCopy("en").soon, "Coming soon – contact Roleflow to join the pilot");
const soon = soonParts(outreacherCopy("en"));
assert.equal(soon.before + soon.link + soon.after, outreacherCopy("en").soon);
assert.equal(soon.link, "contact Roleflow");
const soonEs = soonParts(outreacherCopy("es"));
assert.equal(soonEs.before + soonEs.link + soonEs.after, outreacherCopy("es").soon);
assert.equal(outreachControls({}).soon, true);
assert.equal(outreachControls({}).checkout, false);
assert.equal(outreachControls({}).risk, false);
assert.equal(outreachControls({}).cancel, false);
assert.equal(outreachControls({ outreachCheckoutAvailable: true }).checkout, true);
assert.equal(outreachControls({ outreachCheckoutAvailable: true }).soon, false);
assert.equal(landingCta({ available: false }).label, "Contact us");
assert.equal(landingCta({}).href, "mailto:diego@roleflow.io");
assert.equal(landingCta({ available: true }).label, "Create an account");
const closed = await readOutreachCheckoutStatus(async () => ({ ok: false, json: async () => ({ available: true }) }), { SUPABASE_URL: "https://example.supabase.co", SUPABASE_ANON_KEY: "anon" });
assert.equal(closed.available, false);
const open = await readOutreachCheckoutStatus(async () => ({ ok: true, json: async () => ({ available: true }) }), { SUPABASE_URL: "https://example.supabase.co", SUPABASE_ANON_KEY: "anon" });
assert.equal(open.available, true);
const missing = await readOutreachCheckoutStatus(async () => { throw new Error("down"); }, { SUPABASE_URL: "https://example.supabase.co" });
assert.equal(missing.available, false);
assert.equal(checkoutAvailable({ secret: "", setupPriceId: "price_setup", growthPriceId: "price_growth" }), false);
assert.equal(checkoutAvailable({ secret: "sk_test", setupPriceId: " price_setup ", growthPriceId: "" }), false);
assert.equal(checkoutAvailable({ secret: "sk_test", setupPriceId: "price_setup", growthPriceId: "price_growth" }), true);
assert.match(landing, /\$249 setup \+ 10% of growth, 3-month minimum/);
const termMachine = { minimum_term_ends_at: "2027-02-03T18:00:00.000Z", status: "running" };
assert.match(termCopy(outreacherCopy("en"), termMachine, "en"), /2027/);
assert.match(termCopy(outreacherCopy("en"), { ...termMachine, subscription_cancel_at: "2027-02-03T18:00:00.000Z" }, "en"), /scheduled/i);
const pauseFn = app.slice(app.indexOf("async function saveOutreachPause"), app.indexOf("async function resumeInstagram"));
assert.match(pauseFn, /acq_outreacher_config/);
assert.doesNotMatch(pauseFn, /acq_dm_controls|enabled:/);
const statusAt = checkout.indexOf('body.action === "status"');
const stripeAt = checkout.indexOf("api.stripe.com");
assert.ok(statusAt > 0 && statusAt < stripeAt);
assert.match(checkout, /available: checkoutAvailable/);
assert.match(checkout, /return json\(200, \{\s*available: checkoutAvailable\(/);
